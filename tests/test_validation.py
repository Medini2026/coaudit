def test_no_metrics_means_no_results():
    assert run_validations([], [], Config()) == []


def test_clean_direct_values_get_full_confidence_and_are_auto_approved():
    metrics, results = validate(BALANCED_HTML)
    scored = score_confidence(metrics, results, Config())
    decisions = route(scored, results, Config())
    revenue = next(m for m in scored if m.metric_name == MetricName.REVENUE)
    assert revenue.confidence == 1.0
    assert revenue.confidence_signals["checks"] == 1.0
    assert not any(decision.flagged for decision in decisions)


def test_a_failed_check_lowers_confidence_and_flags_the_value():
    config = Config(year_on_year_threshold=0.05)
    metrics, results = validate(BALANCED_HTML, config)
    scored = score_confidence(metrics, results, config)
    decisions = {d.metric_name: d for d in route(scored, results, config)}
    revenue = next(m for m in scored if m.metric_name == MetricName.REVENUE)
    assert revenue.confidence == 0.5
    assert decisions["revenue"].flagged is True
    assert any("year_on_year" in reason for reason in decisions["revenue"].reasons)


def test_derived_values_are_flagged_for_a_human_look():
    html = BALANCED_HTML.replace(
        "<tr><td>Total liabilities</td><td>600</td><td>580</td></tr>", ""
    )
    metrics, results = validate(html)
    scored = score_confidence(metrics, results, Config())
    decisions = {d.metric_name: d for d in route(scored, results, Config())}
    assert decisions["total_liabilities"].flagged is True
    assert "below the threshold" in decisions["total_liabilities"].reasons[0]


def test_the_confidence_threshold_controls_flagging():
    metrics, results = validate(BALANCED_HTML)
    scored = score_confidence(metrics, results, Config())
    strict = route(scored, results, Config(confidence_threshold=1.0))
    lenient = route(scored, results, Config(confidence_threshold=0.1))
    assert not any(decision.flagged for decision in strict)
    assert not any(decision.flagged for decision in lenient)
    unscored = route(metrics, results, Config())
    assert all(decision.flagged for decision in unscored)


def test_scoring_does_not_change_the_original_metrics():
    metrics, results = validate(BALANCED_HTML)
    score_confidence(metrics, results, Config())
    assert all(metric.confidence is None for metric in metrics)


def test_the_pipeline_returns_scored_metrics_checks_and_decisions(tmp_path):
    html_path = tmp_path / "filing.html"
    html_path.write_text(BALANCED_HTML, encoding="utf-8")
    bundle = build_bundle().model_copy(update={"html_path": str(html_path)})
    analysis = analyze_filing(bundle)
    assert len(analysis.metrics) == 8
    assert len(analysis.decisions) == 8
    assert all(isinstance(metric, ExtractedMetric) for metric in analysis.metrics)
    assert all(metric.confidence is not None for metric in analysis.metrics)
    assert analysis.validations
