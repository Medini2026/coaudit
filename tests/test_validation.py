def test_year_on_year_passes_inside_the_limit_and_fails_outside_it():
    _, results = validate(BALANCED_HTML)
    yoy = {
        result.metrics_involved[0]: result
        for result in results_for(results, CheckName.YEAR_ON_YEAR)
    }
    assert yoy[MetricName.REVENUE].status == CheckStatus.PASSED
    assert yoy[MetricName.OPERATING_INCOME].status == CheckStatus.PASSED
    strict = validate(BALANCED_HTML, Config(year_on_year_threshold=0.05))[1]
    strict_yoy = {
        result.metrics_involved[0]: result
        for result in results_for(strict, CheckName.YEAR_ON_YEAR)
    }
    assert strict_yoy[MetricName.REVENUE].status == CheckStatus.FAILED
    assert "+11.1%" in strict_yoy[MetricName.REVENUE].reason


