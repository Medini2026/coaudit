def test_derived_liabilities_are_not_checked_against_themselves():
    html = BALANCED_HTML.replace(
        "<tr><td>Total liabilities</td><td>600</td><td>580</td></tr>", ""
    )
    metrics, results = validate(html)
    liabilities = next(m for m in metrics if m.metric_name == MetricName.TOTAL_LIABILITIES)
    assert liabilities.extractor == Extractor.DERIVED
