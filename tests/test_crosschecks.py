MINORITY_HTML = (
    FULL_HTML.replace(
        "<tr><td>Net income</td><td>$</td><td>200</td><td>$</td><td>170</td></tr>",
        "<tr><td>Consolidated net income</td><td>210</td><td>178</td></tr>"
        "<tr><td>Net income attributable to noncontrolling interests</td><td>10</td><td>8</td></tr>"
        "<tr><td>Net income attributable to common stockholders</td><td>200</td><td>170</td></tr>",
    ).replace(
        "<tr><td>Net income</td><td>200</td><td>170</td></tr>",
        "<tr><td>Net income</td><td>210</td><td>178</td></tr>",
    )
)


def build_bundle():
    return FilingBundle(
        ticker="EXM",
        cik="0000320193",
        company_name="Example Corp",
        accession_number="0000320193-26-000026",
        url="https://www.sec.gov/Archives/edgar/data/320193/x/doc.htm",
        downloaded_at=datetime(2026, 11, 12, 16, 0, 0),
        document_hash="a" * 64,
        html_path="unused.html",
        fiscal_year_end=PERIOD_END,
    )


def validate(html):
    tables = extract_tables(html)
    metrics = extract_metrics_by_rules(build_bundle(), tables)
    return metrics, run_validations(metrics, tables, Config())


def result_for(results, name):
    return next(result for result in results if result.check_name == name)


def test_consistent_statements_pass_all_three_cross_checks():
    _, results = validate(FULL_HTML)
    for name in (
        CheckName.NET_INCOME_TIE_OUT,
        CheckName.GROSS_PROFIT_IDENTITY,
        CheckName.OPERATING_INCOME_IDENTITY,
    ):
        assert result_for(results, name).status == CheckStatus.PASSED


def test_a_wrong_net_income_fails_the_tie_out_with_the_cash_flow_statement():
    broken = FULL_HTML.replace(
        "<tr><td>Net income</td><td>$</td><td>200</td><td>$</td><td>170</td></tr>",
        "<tr><td>Net income</td><td>$</td><td>170</td><td>$</td><td>170</td></tr>",
    )
    _, results = validate(broken)
    tie_out = result_for(results, CheckName.NET_INCOME_TIE_OUT)
    assert tie_out.status == CheckStatus.FAILED
    assert "does not match" in tie_out.reason
    assert tie_out.metrics_involved == [MetricName.NET_INCOME]


def test_a_gap_equal_to_the_noncontrolling_interest_passes_the_tie_out():
    metrics, results = validate(MINORITY_HTML)
    net_income = next(m for m in metrics if m.metric_name == MetricName.NET_INCOME)
    assert net_income.value == 200_000_000
    tie_out = result_for(results, CheckName.NET_INCOME_TIE_OUT)
    assert tie_out.status == CheckStatus.PASSED
    assert "noncontrolling interest" in tie_out.reason


def test_a_gap_that_is_not_the_minority_interest_fails_the_tie_out():
    broken = MINORITY_HTML.replace(
        "<tr><td>Net income</td><td>210</td><td>178</td></tr>",
        "<tr><td>Net income</td><td>230</td><td>178</td></tr>",
    )
    _, results = validate(broken)
    assert result_for(results, CheckName.NET_INCOME_TIE_OUT).status == CheckStatus.FAILED


def test_a_missing_cash_flow_net_income_line_is_not_applicable():
    html = FULL_HTML.replace("<tr><td>Net income</td><td>200</td><td>170</td></tr>", "")
    _, results = validate(html)
    assert result_for(results, CheckName.NET_INCOME_TIE_OUT).status == CheckStatus.NOT_APPLICABLE


def test_a_wrong_revenue_fails_the_gross_profit_identity():
    broken = FULL_HTML.replace(
        "<tr><td>Total net sales</td><td>$</td><td>1,000</td><td>$</td><td>900</td></tr>",
        "<tr><td>Total net sales</td><td>$</td><td>900</td><td>$</td><td>900</td></tr>",
    )
    _, results = validate(broken)
    identity = result_for(results, CheckName.GROSS_PROFIT_IDENTITY)
    assert identity.status == CheckStatus.FAILED
    assert set(identity.metrics_involved) == {MetricName.REVENUE, MetricName.GROSS_PROFIT}


def test_a_derived_gross_profit_is_not_checked_against_itself():
    html = FULL_HTML.replace("<tr><td>Gross margin</td><td>400</td><td>350</td></tr>", "")
    metrics, results = validate(html)
    gross = next(m for m in metrics if m.metric_name == MetricName.GROSS_PROFIT)
    assert gross.extractor.value == "derived"
    assert (
        result_for(results, CheckName.GROSS_PROFIT_IDENTITY).status == CheckStatus.NOT_APPLICABLE
    )


def test_a_wrong_operating_income_fails_its_identity():
    broken = FULL_HTML.replace(
        "<tr><td>Operating income</td><td>250</td><td>210</td></tr>",
        "<tr><td>Operating income</td><td>210</td><td>210</td></tr>",
    )
    _, results = validate(broken)
    identity = result_for(results, CheckName.OPERATING_INCOME_IDENTITY)
    assert identity.status == CheckStatus.FAILED
    assert "but operating income is" in identity.reason


def test_the_operating_income_identity_uses_total_costs_when_given():
    html = FULL_HTML.replace(
        "<tr><td>Total operating expenses</td><td>150</td><td>140</td></tr>",
        "<tr><td>Total costs and expenses</td><td>750</td><td>690</td></tr>",
    )
    _, results = validate(html)
    identity = result_for(results, CheckName.OPERATING_INCOME_IDENTITY)
    assert identity.status == CheckStatus.PASSED
    assert "total costs" in identity.reason


def test_the_operating_income_identity_handles_a_combined_expense_line():
    html = FULL_HTML.replace(
        "<tr><td>Total operating expenses</td><td>150</td><td>140</td></tr>",
        "<tr><td>Operating, selling, general and administrative expenses</td>"
        "<td>150</td><td>140</td></tr>",
    )
    _, results = validate(html)
    assert (
        result_for(results, CheckName.OPERATING_INCOME_IDENTITY).status == CheckStatus.PASSED
    )


def test_missing_expense_lines_make_the_identity_not_applicable():
    html = FULL_HTML.replace(
        "<tr><td>Total operating expenses</td><td>150</td><td>140</td></tr>", ""
    )
    _, results = validate(html)
    assert (
        result_for(results, CheckName.OPERATING_INCOME_IDENTITY).status
        == CheckStatus.NOT_APPLICABLE
    )


def test_the_cross_checks_catch_wrong_year_errors_that_year_on_year_misses():
    tables = extract_tables(FULL_HTML)
    filing = FilingInput(bundle=build_bundle(), tables=tables)
    outcome = evaluate_all([filing], Config())[0]
    flagged = {
        trial.metric: trial.flagged
        for trial in outcome.trials
        if trial.kind == FaultKind.WRONG_YEAR
    }
    assert flagged[MetricName.REVENUE] is True
    assert flagged[MetricName.GROSS_PROFIT] is True
    assert flagged[MetricName.NET_INCOME] is True
    assert flagged[MetricName.OPERATING_INCOME] is True
    assert flagged[MetricName.TOTAL_ASSETS] is True
