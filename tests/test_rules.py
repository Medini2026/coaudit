def build_bundle(period_end=date(2026, 9, 26)):
    return FilingBundle(
        ticker="EXM",
        cik="0000320193",
        company_name="Example Corp",
        accession_number="0000320193-26-000026",
        url="https://www.sec.gov/Archives/edgar/data/320193/x/doc.htm",
        downloaded_at=datetime(2026, 11, 12, 16, 0, 0),
        document_hash="a" * 64,
        html_path="unused.html",
        fiscal_year_end=period_end,
    )


def extract(html, period_end=date(2026, 9, 26)):
    metrics = extract_metrics_by_rules(build_bundle(period_end), extract_tables(html))
    return {metric.metric_name: metric for metric in metrics}


def test_all_eight_metrics_are_found_and_scaled_to_dollars():
    found = extract(STATEMENTS_HTML)
    assert set(found) == set(MetricName)
    assert found[MetricName.REVENUE].value == 1_000_000_000
    assert found[MetricName.NET_INCOME].value == 200_000_000
    assert found[MetricName.TOTAL_ASSETS].value == 900_000_000
    assert found[MetricName.TOTAL_LIABILITIES].value == 600_000_000
    assert found[MetricName.SHAREHOLDERS_EQUITY].value == 300_000_000
    assert found[MetricName.OPERATING_CASH_FLOW].value == 320_000_000
    assert found[MetricName.GROSS_PROFIT].value == 400_000_000
    assert found[MetricName.OPERATING_INCOME].value == 250_000_000


def test_prior_year_values_are_kept():
    found = extract(STATEMENTS_HTML)
    assert found[MetricName.REVENUE].prior_value == 900_000_000
    assert found[MetricName.TOTAL_ASSETS].prior_value == 850_000_000
    assert found[MetricName.OPERATING_CASH_FLOW].prior_value == 300_000_000


def test_each_metric_carries_period_unit_and_source():
    revenue = extract(STATEMENTS_HTML)[MetricName.REVENUE]
    assert revenue.period_end == date(2026, 9, 26)
    assert revenue.fiscal_label == "FY2026"
    assert revenue.unit_scale == 1_000_000
    assert "Total net sales" in revenue.source_snippet
    assert revenue.source_location.row_index == 0
    assert revenue.extractor == Extractor.PARSER
    assert revenue.confidence is None


def test_net_income_ignores_the_per_share_row():
    assert extract(STATEMENTS_HTML)[MetricName.NET_INCOME].value == 200_000_000


def test_equity_ignores_the_liabilities_and_equity_total():
    assert extract(STATEMENTS_HTML)[MetricName.SHAREHOLDERS_EQUITY].value == 300_000_000


def test_operating_cash_flow_ignores_the_adjustments_row():
    found = extract(STATEMENTS_HTML)
    assert found[MetricName.OPERATING_CASH_FLOW].value == 320_000_000


def test_total_liabilities_is_derived_when_the_line_is_missing():
    html = STATEMENTS_HTML.replace(
        "<tr><td>Total liabilities</td><td></td><td>600</td><td></td><td></td><td>580</td></tr>",
        "",
    )
    liabilities = extract(html)[MetricName.TOTAL_LIABILITIES]
    assert liabilities.extractor == Extractor.DERIVED
    assert liabilities.value == 600_000_000
    assert liabilities.prior_value == 580_000_000
    assert liabilities.derived_from == [
        MetricName.TOTAL_ASSETS,
        MetricName.SHAREHOLDERS_EQUITY,
    ]


def test_missing_statements_are_skipped_without_error():
    html = """
    <p>CONSOLIDATED BALANCE SHEETS</p>
    <table>
    <tr><td>Total assets</td><td>900</td></tr>
    <tr><td>Total liabilities</td><td>600</td></tr>
    </table>
    """
    found = extract(html)
    assert MetricName.TOTAL_ASSETS in found
    assert MetricName.REVENUE not in found
    assert MetricName.OPERATING_CASH_FLOW not in found


def test_no_period_end_means_no_metrics():
    metrics = extract_metrics_by_rules(
        build_bundle(period_end=None), extract_tables(STATEMENTS_HTML)
    )
    assert metrics == []


