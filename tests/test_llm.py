def test_real_row_with_a_different_value_fails_the_check():
    bundle, tables, metrics = setup()
    readings = [
        {"metric": "revenue", "row_label": "Operating income", "value": 250},
    ]
    extras, results = second_reading(bundle, tables, metrics, FakeClient(readings))
    revenue = by_name(results)[MetricName.REVENUE]
    assert revenue.status == CheckStatus.FAILED
    assert "250,000,000" in revenue.reason
    assert "1,000,000,000" in revenue.reason


def test_metrics_the_model_leaves_out_are_not_applicable():
    bundle, tables, metrics = setup()
    extras, results = second_reading(bundle, tables, metrics, FakeClient(CORRECT[:1]))
    statuses = by_name(results)
    assert statuses[MetricName.REVENUE].status == CheckStatus.PASSED
    assert statuses[MetricName.NET_INCOME].status == CheckStatus.NOT_APPLICABLE


def test_model_failure_never_breaks_the_run():
    bundle, tables, metrics = setup()
    extras, results = second_reading(
        bundle, tables, metrics, FakeClient(error=LlmError("Could not reach the model service"))
    )
    assert extras == []
    assert len(results) == 1
    assert results[0].status == CheckStatus.NOT_APPLICABLE
    assert "unavailable" in results[0].reason


def test_response_without_a_readings_list_is_an_error():
    bundle, tables, _ = setup()

    class Broken:
        def complete_json(self, prompt):
            return {"answer": 1}

    with pytest.raises(LlmError):
        read_with_llm(bundle, tables, Broken())


def test_llm_metrics_are_marked_as_llm_extracted():
    bundle, tables, _ = setup()
    reading = read_with_llm(bundle, tables, FakeClient(CORRECT))
    assert len(reading.metrics) == 8
    assert all(metric.extractor == Extractor.LLM for metric in reading.metrics)


def test_a_failed_second_reading_flags_the_metric_for_review():
    bundle, tables, _ = setup()
    readings = [{"metric": "revenue", "row_label": "Operating income", "value": 250}]
    analysis = analyze_filing(bundle, Config(), tables, FakeClient(readings))
    flagged = {decision.metric_name: decision for decision in analysis.decisions}
    assert flagged["revenue"].flagged
    assert any("second_reading" in reason for reason in flagged["revenue"].reasons)


def test_analysis_without_a_client_has_no_second_reading_checks():
    bundle, tables, _ = setup()
    analysis = analyze_filing(bundle, Config(), tables)
    assert all(v.check_name != CheckName.SECOND_READING for v in analysis.validations)


def test_analysis_with_a_matching_client_records_passed_second_readings():
    bundle, tables, _ = setup()
    analysis = analyze_filing(bundle, Config(), tables, FakeClient(CORRECT))
    second = [v for v in analysis.validations if v.check_name == CheckName.SECOND_READING]
    assert len(second) == 8
    assert all(v.status == CheckStatus.PASSED for v in second)


def test_json_text_parsing():
    assert parse_json_text('{"a": 1}') == {"a": 1}
    assert parse_json_text('```json\n{"a": 1}\n```') == {"a": 1}
    with pytest.raises(LlmError):
        parse_json_text("not json")
    with pytest.raises(LlmError):
        parse_json_text("[1, 2]")


def gemini_transport(captured):
    def handler(request):
        captured.append(request)
        if request.method == "GET":
            return httpx.Response(
                200,
                json={
                    "models": [
                        {"name": "models/gemini-2.0-flash", "supportedGenerationMethods": ["generateContent"]},
                        {"name": "models/gemini-2.5-flash", "supportedGenerationMethods": ["generateContent"]},
                        {"name": "models/gemini-2.5-flash-lite", "supportedGenerationMethods": ["generateContent"]},
                        {"name": "models/gemini-2.5-pro", "supportedGenerationMethods": ["generateContent"]},
                    ]
                },
            )
        text = json.dumps({"readings": []})
        return httpx.Response(200, json={"candidates": [{"content": {"parts": [{"text": text}]}}]})

    return httpx.MockTransport(handler)


def test_gemini_picks_a_flash_model_and_returns_json():
    captured = []
    client = GeminiClient("test-key", transport=gemini_transport(captured))
    assert client.complete_json("hello") == {"readings": []}
    assert client.model == "models/gemini-2.5-flash"
    assert captured[-1].url.path.endswith("models/gemini-2.5-flash:generateContent")
    assert captured[-1].headers["x-goog-api-key"] == "test-key"
    assert "test-key" not in str(captured[-1].url)


def test_gemini_uses_the_model_given_in_the_environment_setting():
    captured = []
    client = GeminiClient("test-key", "gemini-2.5-pro", transport=gemini_transport(captured))
    client.complete_json("hello")
    assert len(captured) == 1
    assert captured[0].url.path.endswith("models/gemini-2.5-pro:generateContent")


def test_http_errors_become_llm_errors_without_leaking_the_key():
    transport = httpx.MockTransport(lambda request: httpx.Response(403, json={"error": "denied"}))
    client = OpenAIClient("secret-key-123", transport=transport)
    with pytest.raises(LlmError) as error:
        client.complete_json("hello")
    assert "403" in str(error.value)
    assert "secret-key-123" not in str(error.value)


def test_network_failure_becomes_an_llm_error():
    def handler(request):
        raise httpx.ConnectError("offline")

    client = AnthropicClient("test-key", transport=httpx.MockTransport(handler))
    with pytest.raises(LlmError):
        client.complete_json("hello")


def test_openai_and_anthropic_response_shapes():
    openai = OpenAIClient(
        "k",
        transport=httpx.MockTransport(
            lambda request: httpx.Response(
                200, json={"choices": [{"message": {"content": '{"readings": []}'}}]}
            )
        ),
    )
    assert openai.complete_json("x") == {"readings": []}
    anthropic = AnthropicClient(
        "k",
        transport=httpx.MockTransport(
            lambda request: httpx.Response(200, json={"content": [{"text": '{"readings": []}'}]})
        ),
    )
    assert anthropic.complete_json("x") == {"readings": []}


