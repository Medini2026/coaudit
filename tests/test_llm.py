CORRECT = [
    {"metric": "revenue", "row_label": "Total net sales", "value": 1000},
    {"metric": "net_income", "row_label": "Net income", "value": 200},
    {"metric": "total_assets", "row_label": "Total assets", "value": 900},
    {"metric": "total_liabilities", "row_label": "Total liabilities", "value": 600},
    {"metric": "shareholders_equity", "row_label": "Total shareholders’ equity", "value": 300},
    {"metric": "operating_cash_flow", "row_label": "Cash generated by operating activities", "value": 320},
    {"metric": "gross_profit", "row_label": "Gross margin", "value": 400},
    {"metric": "operating_income", "row_label": "Operating income", "value": 250},
]


class FakeClient:
    def __init__(self, readings=None, error=None):
        self.readings = readings
        self.error = error
        self.prompts = []

    def complete_json(self, prompt):
        self.prompts.append(prompt)
        if self.error:
            raise self.error
        return {"readings": self.readings}


def setup():
    bundle = build_bundle()
    tables = extract_tables(STATEMENTS_HTML)
    return bundle, tables, extract_metrics_by_rules(bundle, tables)


def by_name(results):
    return {result.metrics_involved[0]: result for result in results if result.metrics_involved}


def test_matching_reading_passes_every_metric():
    bundle, tables, metrics = setup()
    extras, results = second_reading(bundle, tables, metrics, FakeClient(CORRECT))
    assert extras == []
    assert len(results) == 8
    assert all(result.status == CheckStatus.PASSED for result in results)
    assert all(result.check_name == CheckName.SECOND_READING for result in results)


def test_prompt_contains_the_tables_and_metric_keys():
    bundle, tables, _ = setup()
    client = FakeClient(CORRECT)
    read_with_llm(bundle, tables, client)
    assert "Total net sales" in client.prompts[0]
    assert "operating_cash_flow" in client.prompts[0]


def test_number_not_in_the_table_is_rejected_by_the_grounding_check():
    bundle, tables, _ = setup()
    readings = [{"metric": "revenue", "row_label": "Total net sales", "value": 9999}]
    reading = read_with_llm(bundle, tables, FakeClient(readings))
    assert reading.metrics == []
    assert reading.rejected[0][0] == "revenue"


