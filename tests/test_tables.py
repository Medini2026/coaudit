def test_titles_are_found_from_the_text_before_the_table():
    tables = extract_tables(FILING_HTML)
    assert tables[1].title == "CONSOLIDATED STATEMENTS OF OPERATIONS"
    assert tables[2].title == "CONSOLIDATED BALANCE SHEETS"


def test_rows_keep_labels_values_and_positions():
    balance_sheet = extract_tables(FILING_HTML)[2]
    total_assets = next(row for row in balance_sheet.rows if row.label == "Total assets")
    assert total_assets.values == (900.0, 850.0)
    assert balance_sheet.rows[total_assets.index] is total_assets


def test_negative_cash_flow_values_are_read():
    cash_flow = extract_tables(FILING_HTML)[3]
    investing = next(row for row in cash_flow.rows if "investing" in row.label)
    assert investing.values == (-120.0, -100.0)


def test_select_prefers_the_table_with_more_rows():
    tables = extract_tables(FILING_HTML)
    summary_html = """
    <p>Balance Sheet Summary</p>
    <table>
    <tr><td>Total assets</td><td>1</td></tr>
    <tr><td>Total liabilities</td><td>1</td></tr>
    </table>
    """
    summary = extract_tables(summary_html)[0]
    chosen = select_statement_tables([summary] + tables)
    assert chosen[TableKind.BALANCE_SHEET].table_id == "t0002"


def test_select_returns_only_found_kinds():
    html = "<table><tr><td>Total assets</td><td>1</td></tr><tr><td>Total liabilities</td><td>1</td></tr></table>"
    chosen = select_statement_tables(extract_tables(html))
    assert list(chosen) == [TableKind.BALANCE_SHEET]


def test_classify_returns_other_for_unrelated_tables():
    rows = [parse_row(0, ["Employees", "1,000"])]
    assert classify_table(rows) == TableKind.OTHER


def test_table_refs_match_the_contract():
    refs = table_refs(extract_tables(FILING_HTML))
    assert all(isinstance(ref, TableRef) for ref in refs)
    assert refs[2].kind == TableKind.BALANCE_SHEET
    assert refs[2].row_count == 6
    assert refs[2].unit_scale == 1_000_000


def test_load_tables_reads_the_saved_filing(tmp_path):
    html_path = tmp_path / "filing.html"
    html_path.write_text(FILING_HTML, encoding="utf-8")
    bundle = FilingBundle(
        ticker="EXM",
        cik="0000320193",
        company_name="Example Corp",
        accession_number="0000320193-25-000079",
        url="https://www.sec.gov/Archives/edgar/data/320193/x/doc.htm",
        downloaded_at=datetime(2026, 11, 12, 16, 0, 0),
        document_hash="a" * 64,
        html_path=str(html_path),
    )
    assert len(load_tables(bundle)) == 5
