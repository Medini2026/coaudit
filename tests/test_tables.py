@pytest.mark.parametrize(
    "text, expected",
    [
        ("1,234", 1234.0),
        ("(1,234)", -1234.0),
        ("(1,234", -1234.0),
        ("-5", -5.0),
        ("−5", -5.0),
        ("—", 0.0),
        ("$ 1,234.50", 1234.5),
        ("1.25", 1.25),
    ],
)
def test_parse_number_reads_filing_formats(text, expected):
    assert parse_number(text) == expected


@pytest.mark.parametrize("text", ["$", ")", "(", "", "12.5%", "Total assets", "Note 3"])
def test_parse_number_ignores_non_numbers(text):
    assert parse_number(text) is None


def test_parse_row_merges_split_cells():
    row = parse_row(0, ["Total assets", "$", "359", "", "$", "364"])
    assert row.label == "Total assets"
    assert row.values == (359.0, 364.0)


def test_parse_row_reads_negative_numbers_split_across_cells():
    row = parse_row(3, ["Net loss", "(1,234", ")", "(10", ")"])
    assert row.label == "Net loss"
    assert row.values == (-1234.0, -10.0)


def test_parse_row_drops_percentage_columns():
    row = parse_row(1, ["Americas", "198,083", "11", "%", "178,353"])
    assert row.label == "Americas"
    assert row.values == (198083.0, 178353.0)


def test_parse_row_drops_negative_percentage_columns():
    row = parse_row(2, ["Europe", "100", "(7", ")%", "108"])
    assert row.values == (100.0, 108.0)


def test_detect_unit_scale():
    assert detect_unit_scale("(In millions, except per share)") == 1_000_000
    assert detect_unit_scale("amounts in thousands") == 1_000
    assert detect_unit_scale("in billions") == 1_000_000_000
    assert detect_unit_scale("no unit here") is None


def test_extract_tables_classifies_each_statement():
    tables = extract_tables(FILING_HTML)
    kinds = [table.kind for table in tables]
    assert kinds == [
        TableKind.OTHER,
        TableKind.INCOME_STATEMENT,
        TableKind.BALANCE_SHEET,
        TableKind.CASH_FLOW,
        TableKind.SEGMENT_NOTE,
    ]


def test_table_of_contents_is_not_mistaken_for_a_statement():
    tables = extract_tables(FILING_HTML)
    assert tables[0].kind == TableKind.OTHER


def test_unit_scale_comes_from_the_table_or_the_text_before_it():
    tables = extract_tables(FILING_HTML)
    assert tables[1].unit_scale == 1_000_000
    assert tables[2].unit_scale == 1_000_000
    assert tables[0].unit_scale == 1


